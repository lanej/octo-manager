import { mkdir, readFile, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { IssueStage, Waiting } from "../src/issues/contracts.js";
import { EntryState } from "../src/merging/contracts.js";
import type { MessagePresentation } from "../src/merging/receipt-types.js";
import type { AgentMessage } from "../src/notifications/message.js";
import { renderDigest } from "../src/notifications/render.js";
import {
  NoticeSchema,
  renderNotice,
  type SafeNotice,
} from "../src/security/notifications.js";

const pr = "https://github.com/owner/repo/pull/42";
const head = "a".repeat(40);
const receipt = "1234abcd-1111-4111-8111-111111111111";
const directory = join(homedir(), ".local/state/octo-manager");
const target = new URL(
  "../docs/generated/agent-message-examples.md",
  import.meta.url,
);
const id = (index: number) =>
  `${index.toString(16).padStart(8, "0")}-1111-4111-8111-111111111111`;
const contexts: Record<SafeNotice["kind"], Partial<SafeNotice>> = {
  conflict: {},
  check_failed: { assessment: "pending" },
  changes_requested: {},
  review_feedback: { assessment: "pending" },
  checks_passed: {},
  checks_completed: {},
  participants: {},
  submission: {
    subject: { kind: "submission", id: id(10) },
  },
  merge: { subject: { kind: "merge_entry", id: id(11) } },
  update: {},
  issue: {
    issueStage: IssueStage.Investigation,
    issueWaiting: Waiting.Clarification,
    subject: { kind: "issue", id: id(12) },
  },
};
const readiness = {
  ready: "ready",
  review_unavailable: "review_unavailable",
  blocked: "blocked",
  feedback_assessment: "feedback_assessment",
} satisfies { [State in NonNullable<MessagePresentation["status"]>]: State };

function message(
  kind: SafeNotice["kind"],
  index = 1,
  override: Partial<SafeNotice> = {},
): AgentMessage {
  return {
    id: id(index),
    actionId: [
      "conflict",
      "check_failed",
      "changes_requested",
      "review_feedback",
      "checks_passed",
      "checks_completed",
    ].includes(kind)
      ? id(index + 100)
      : "",
    recipientAgentId: id(200),
    sequence: index,
    body: "Synthetic evidence is retained for explicit retrieval, not rendered here.",
    createdAt: 1,
    nextCheckAt: 1,
    applicable: true,
    notice: {
      version: 1,
      kind,
      assessment: "not_required",
      ...(kind === "issue" || kind === "submission" || kind === "update"
        ? {}
        : { prUrl: pr, head }),
      role: "owner",
      ...contexts[kind],
      ...override,
    },
  };
}
function quoted(body: string): string {
  return body
    .split("\n")
    .map((line) => (line === "" ? ">" : `> ${line}`))
    .join("\n>\n");
}
function queued(
  rows: AgentMessage[],
  state = directory,
  presentation?: MessagePresentation,
): string {
  return renderDigest(
    rows,
    state,
    receipt,
    presentation === undefined ? undefined : () => presentation,
  ).body;
}
export function messageDocumentation(): string {
  const kinds = NoticeSchema.properties.kind.anyOf.map((kind) => kind.const);
  const lines = [
    "<!-- Generated by scripts/generate-message-docs.ts; do not edit. -->",
    "# Generated agent message examples",
    "These synthetic examples come from the production queued and direct renderers. They demonstrate content, not live delivery eligibility or merge authority. IDs, PRs and commits are illustrative; no external feedback or local host paths are captured.",
    "Regenerate with `bun scripts/generate-message-docs.ts` or `bun run generate`. Verify with `bun scripts/generate-message-docs.ts --check`; `bun run check` runs that freshness check in CI.",
    "See the [agent message standard](../agent-messages.md) for delivery eligibility, typed evidence retrieval and receipt semantics. Each rendered line is shown as a paragraph so links and commands remain usable.",
    "## Queued notice kinds",
    "Every kind in the notice schema is represented below. Fixed reasons share one public read command; internal status and operator instructions stay in retrieval.",
  ];
  for (const kind of kinds)
    lines.push(`### ${kind}`, quoted(queued([message(kind)])));
  lines.push(
    "### Confirmed merge",
    quoted(queued([message("merge", 1, { mergeState: EntryState.Merged })])),
    "## Readiness states",
    "These are presentation fixtures; rendering a Ready label neither checks eligibility nor executes a merge.",
  );
  for (const status of Object.values(readiness)) {
    lines.push(
      `### ${status}`,
      quoted(queued([message("checks_passed")], directory, { status })),
    );
  }
  lines.push(
    "## Grouping and link variants",
    "### Three feedback items",
    quoted(
      queued([
        message("review_feedback", 1),
        message("review_feedback", 2),
        message("review_feedback", 3),
      ]),
    ),
    "### Several reasons and PRs",
    quoted(
      queued([
        message("review_feedback"),
        message("check_failed", 2),
        message("conflict", 3, {
          prUrl: "https://github.com/owner/repo/pull/43",
        }),
      ]),
    ),
    "### PR without a validated commit",
    quoted(queued([message("review_feedback", 1, { head: "invalid" })])),
    "### Custom state directory",
    quoted(queued([message("review_feedback")], "/var/lib/octo demo")),
    "## Compatible direct notices",
    "Direct delivery retains its existing markers and fields. These are direct-item examples, not the queued format. This catalog covers kinds and readiness states, with representative field values rather than every combination of stages, roles and assessment states.",
  );
  for (const kind of kinds) {
    const row = message(kind);
    if (row.notice === undefined) throw new Error("Missing notice fixture");
    lines.push(
      `### Direct ${kind}`,
      quoted(renderNotice(row.notice, row.id, row.actionId)),
    );
  }
  return lines.join("\n\n") + "\n";
}
export async function updateMessageDocumentation(
  check: boolean,
  output = target,
): Promise<void> {
  const expected = messageDocumentation();
  if (check) {
    let current: string | undefined;
    try {
      current = await readFile(output, "utf8");
    } catch (error) {
      if (
        !(error instanceof Error) ||
        !("code" in error) ||
        error.code !== "ENOENT"
      )
        throw error;
    }
    if (current !== expected)
      throw new Error(
        "Generated agent message examples are stale; run bun scripts/generate-message-docs.ts",
      );
    return;
  }
  await mkdir(dirname(fileURLToPath(output)), { recursive: true });
  await writeFile(output, expected);
}
if (import.meta.main) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check") || args.length > 1)
    throw new Error("Usage: bun scripts/generate-message-docs.ts [--check]");
  await updateMessageDocumentation(args.includes("--check"));
}
